"""DocWriter and RiskAnalyst."""
from __future__ import annotations

from ..models import Artifact, Task
from .base import Agent, AgentContext


class DocWriter(Agent):
    name = "doc_writer"

    def run(self, task: Task, ctx: AgentContext) -> list[Artifact]:
        if task.inputs.get("mode") == "change":
            return self._changelog(task, ctx)
        spec = ctx.blackboard.require("spec")
        contract = ctx.blackboard.require("api_contract")
        p = spec["parameters"]
        rows = []
        for path, ops in contract["paths"].items():
            for method, op in ops.items():
                codes = ", ".join(op["responses"])
                auth = "API key" if op.get("security") else "public"
                rows.append(f"| `{method.upper()}` | `{path}` | {op['operationId']} | {auth} | {codes} |")
        readme = f"""# URL Shortener Service

Generated by **agentic-sdlc** from the requirement:

> {spec['raw']}

## Features
{chr(10).join('- ' + f for f in spec['functional'])}

## Quick start

```bash
cd service
python -m venv .venv && source .venv/bin/activate
pip install -r requirements.txt
export SHORTENER_API_KEYS=dev-key-123          # write endpoints need X-API-Key
uvicorn app.main:app --reload --port 8000
```

PowerShell:

```powershell
cd service
python -m venv .venv; .\\.venv\\Scripts\\Activate.ps1
pip install -r requirements.txt
$env:SHORTENER_API_KEYS = "dev-key-123"
uvicorn app.main:app --reload --port 8000
```

Try it:

```bash
curl -s -X POST localhost:8000/api/v1/links -H 'X-API-Key: dev-key-123' \\
     -H 'Content-Type: application/json' -d '{{"url":"https://example.com/docs","ttl_days":30}}'
curl -si localhost:8000/<code>                  # {p['redirect_status']} + Location header
curl -s  localhost:8000/api/v1/links/<code>/stats
```

```powershell
$r = Invoke-RestMethod -Method Post http://localhost:8000/api/v1/links -Headers @{{"X-API-Key"="dev-key-123"}} `
     -ContentType "application/json" -Body '{{"url":"https://example.com/docs","ttl_days":30}}'
Invoke-WebRequest "http://localhost:8000/$($r.code)" -MaximumRedirection 0 -SkipHttpErrorCheck
Invoke-RestMethod "http://localhost:8000/api/v1/links/$($r.code)/stats"
```

Docker: `docker build -t url-shortener . && docker run -p 8000:8000 -e SHORTENER_API_KEYS=k url-shortener`

## API (contract: `openapi.yaml`, live docs at `/docs`)

| Method | Path | Operation | Auth | Responses |
|---|---|---|---|---|
{chr(10).join(rows)}

Errors always use `{{"error": {{"code": "...", "message": "..."}}}}`.

## Configuration

| Env var | Default | Meaning |
|---|---|---|
| `SHORTENER_DB_PATH` | `shortener.db` | SQLite file (dev); use the PostgreSQL adapter in production |
| `SHORTENER_BASE_URL` | `http://localhost:8000` | Prefix for `short_url` |
| `SHORTENER_CODE_LENGTH` | `{p['code_length']}` | Random base62 code length |
| `SHORTENER_REDIRECT_STATUS` | `{p['redirect_status']}` | 301 or 302 (see ADR-002) |
| `SHORTENER_DEFAULT_TTL_DAYS` | `{p['default_ttl_days']}` | Default expiry when the request omits `ttl_days` |
| `SHORTENER_RATE_LIMIT` | `{p['rate_limit_per_min']}` | Link creations per minute per key/IP |
| `SHORTENER_REQUIRE_API_KEY` | `{p['require_api_key']}` | Require `X-API-Key` on writes |
| `SHORTENER_API_KEYS` | (empty) | Comma-separated valid keys |
| `SHORTENER_VISITOR_SALT` | `change-me` | Salt for visitor hashing - **set in production** |

## Tests

```bash
pytest -q                     # unit + integration
pytest tests/unit -q          # fast unit tests only
```

## Operations runbook
- Health: `GET /healthz` (container HEALTHCHECK uses it).
- Abuse: tune `SHORTENER_RATE_LIMIT`; deactivate a link with `DELETE /api/v1/links/{{code}}` (takes effect
  within the cache TTL, 300 s, on other instances).
- Shutdown flushes buffered click events; a hard kill can lose at most one analytics batch.
- See `docs/ARCHITECTURE.md` for design decisions and the scaling path.
"""
        api_md = ["# API reference", "", "Source of truth: `openapi.yaml` (OpenAPI 3.1).", ""]
        for name, schema in contract["components"]["schemas"].items():
            api_md += [f"## {name}", "", "| Field | Type |", "|---|---|"]
            for f, s in schema.get("properties", {}).items():
                api_md.append(f"| `{f}` | {s.get('type', 'object')} |")
            api_md.append("")
        return [self.write(ctx, task, "service/README.md", readme, "doc"),
                self.write(ctx, task, "service/docs/API.md", "\n".join(api_md), "doc")]

    def _changelog(self, task: Task, ctx: AgentContext) -> list[Artifact]:
        design = ctx.blackboard.require("change_design")
        ws = ctx.workspace
        changelog = ["# Changelog", "", "## v1.1.0", "", "### Added",
                     "- Optional link expiry: `Shortener.shorten(url, ttl_seconds=...)`, `POST /shorten` accepts "
                     "`ttl_seconds`; expired codes return **410 Gone**.",
                     "- `Shortener.status(code)` -> `active | expired | missing`.",
                     "- Injectable `clock` for deterministic tests.", "", "### Fixed",
                     "- Hash collisions no longer overwrite an existing link for a different URL (bounded re-hash).",
                     "", "### Compatibility", *[f"- {c}" for c in design["compatibility"]], ""]
        readme = ws.read("patched_repo/README.md").replace(
            "Known issues: links never expire; hash collisions are not handled.",
            "Links can expire (`ttl_seconds`); expired codes return 410. Hash collisions are resolved by "
            "re-hashing, never by overwriting.\n\n```bash\ncurl -X POST localhost:8080/shorten -d "
            "'{\"url\":\"https://example.com\",\"ttl_seconds\":3600}'\n```")
        return [self.write(ctx, task, "patched_repo/CHANGELOG.md", "\n".join(changelog), "doc"),
                self.write(ctx, task, "patched_repo/README.md", readme, "doc")]


class RiskAnalyst(Agent):
    name = "risk_analyst"

    def run(self, task: Task, ctx: AgentContext) -> list[Artifact]:
        spec = ctx.blackboard.require("spec")
        if spec["scenario"] == "brownfield":
            risks = self._brownfield(ctx)
        else:
            risks = self._greenfield(spec["parameters"])
        llm_extra = ctx.llm.complete_json("You are a staff engineer doing a risk review.",
                                          f"Return up to 3 extra risks as JSON list of objects with keys "
                                          f"risk, likelihood, impact, mitigation, failure_scenario for: {spec['raw']}")
        if isinstance(llm_extra, list):
            risks += [r for r in llm_extra if isinstance(r, dict) and "risk" in r][:3]
        ctx.blackboard.put("risks", risks, producer=task.id)
        md = ["# Risk register", "", "| # | Risk | L | I | Failure scenario | Mitigation |", "|---|---|---|---|---|---|"]
        for i, r in enumerate(risks, 1):
            md.append(f"| R{i} | {r['risk']} | {r['likelihood']} | {r['impact']} | {r['failure_scenario']} | "
                      f"{r['mitigation']} |")
        out = "service/docs/RISKS.md" if spec["scenario"] != "brownfield" else "analysis/RISKS.md"
        return [self.write(ctx, task, out, "\n".join(md) + "\n", "doc")]

    @staticmethod
    def _greenfield(p: dict) -> list[dict]:
        r = [
            {"risk": "Open redirect / phishing abuse", "likelihood": "H", "impact": "H",
             "failure_scenario": "Attackers mint links to malicious sites; domain gets blocklisted",
             "mitigation": "API keys on create, rate limiting, scheme/host validation; add URL reputation hook"},
            {"risk": "SSRF via preview/unfurl features", "likelihood": "M", "impact": "H",
             "failure_scenario": "Internal hosts reachable through crafted links",
             "mitigation": "Private/loopback/link-local destinations rejected at creation"},
            {"risk": "Code collisions as table grows", "likelihood": "L", "impact": "M",
             "failure_scenario": f"Birthday bound for 62^{p['code_length']} space reached; creates fail with 503",
             "mitigation": "PK-enforced uniqueness, bounded retries, alert on retry rate, raise code length"},
            {"risk": "SQLite single-writer bottleneck", "likelihood": "H (at scale)", "impact": "H",
             "failure_scenario": "Write lock contention > ~1k writes/s; latency spikes",
             "mitigation": "Repository port: PostgreSQL adapter in production; SQLite only for dev/test"},
            {"risk": "Analytics event loss", "likelihood": "M", "impact": "L",
             "failure_scenario": "Process killed with a non-empty buffer; up to one batch of clicks lost",
             "mitigation": "Flush on shutdown, bounded batch size; Kafka producer with acks=all in production"},
            {"risk": "Stale cache after deactivation", "likelihood": "M", "impact": "M",
             "failure_scenario": "Deactivated link redirects on other instances until cache TTL",
             "mitigation": "Short cache TTL (300 s); pub/sub invalidation with Redis at scale"},
            {"risk": "Hot links (viral traffic)", "likelihood": "M", "impact": "M",
             "failure_scenario": "One code receives most traffic; DB/cache hotspot",
             "mitigation": "Read-through cache absorbs reads; CDN edge caching if 301 adopted"},
            {"risk": "Privacy / GDPR", "likelihood": "M", "impact": "H",
             "failure_scenario": "Storing raw IPs makes the click store personal data",
             "mitigation": "Only salted IP hashes and referrer host stored; 90-day raw-event retention"},
            {"risk": "In-process rate limiter per instance", "likelihood": "H", "impact": "L",
             "failure_scenario": "Effective limit = N x limit across N instances",
             "mitigation": "Redis-backed token bucket when running > 1 instance"},
        ]
        if p["redirect_status"] == 301:
            r.append({"risk": "301 caching hides clicks", "likelihood": "H", "impact": "M",
                      "failure_scenario": "Browsers cache redirects; analytics under-counts, deactivation ignored",
                      "mitigation": "Prefer 302 when analytics matter"})
        return r

    @staticmethod
    def _brownfield(ctx: AgentContext) -> list[dict]:
        impact = ctx.blackboard.require("impact")
        return [
            {"risk": "Behaviour change for existing callers", "likelihood": "L", "impact": "H",
             "failure_scenario": "A caller relying on overwrite-on-collision now gets a different code",
             "mitigation": "Only *different* URLs are re-hashed; same-URL idempotency kept; regression suite"},
            {"risk": "Custom stores without expiry support", "likelihood": "M", "impact": "M",
             "failure_scenario": "Third-party store lacks get_record()/expires_at",
             "mitigation": "Duck-typed fallback; ttl on such stores raises a clear ValueError"},
            {"risk": "Memory growth from expired links", "likelihood": "M", "impact": "L",
             "failure_scenario": "Expired records are never purged from the in-memory dict",
             "mitigation": "Lazy reuse of expired slots; follow-up: periodic sweeper (out of scope)"},
            {"risk": "Clock skew / wall-clock jumps", "likelihood": "L", "impact": "M",
             "failure_scenario": "NTP step makes links expire early/late",
             "mitigation": "Injectable clock; TTL semantics documented as wall-clock seconds"},
            {"risk": f"Blast radius across {len(impact['impacted_code_modules'])} modules", "likelihood": "L",
             "impact": "M", "failure_scenario": "Regression in HTTP layer",
             "mitigation": "HTTP-level tests start a real server; rollback = revert changes.patch"},
        ]
